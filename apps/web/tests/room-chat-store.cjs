const assert=require('node:assert/strict'),fs=require('node:fs/promises'),os=require('node:os'),path=require('node:path'),{randomUUID,createHash}=require('node:crypto');
const {load}=require('./load-typescript.cjs');
(async()=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'castlink-room-chat-'));
 process.env.STUDIOLINK_DATA_DIR=root;
 const scope={studioId:'studio-one',roomAssociation:'room-one'},now=1800000000000;
 const message=(text='Hello')=>({id:randomUUID(),message:text,identity:'guest-one',name:'Caster'});
 const filename=s=>path.join(root,'runtime','room-chat',createHash('sha256').update(JSON.stringify([s.studioId,s.roomAssociation])).digest('hex')+'.json');
 try{
  const chat=load('../lib/room-chat-store.ts');
  assert.equal(chat.ROOM_CHAT_RETENTION_MS,86400000);
  assert.deepEqual(await chat.readRoomChat(scope,now),[]);
  const input=message(),first=await chat.appendRoomChat(scope,{...input,timestamp:1},now);
  assert.equal(first.timestamp,now,'caller timestamp is ignored');
  assert.deepEqual(await chat.appendRoomChat(scope,input,now+20),first,'retry returns original timestamp');
  await assert.rejects(chat.appendRoomChat(scope,{...input,message:'Different'},now+30),/conflict/i);
  await assert.rejects(chat.appendRoomChat(scope,{...input,identity:'guest-two'},now+1),/conflict/i,'room message IDs are globally unique');
  assert.deepEqual(await chat.appendRoomChat(scope,{...input,name:'Renamed caster'},now+1),first,'retries preserve original author name');
  await chat.appendRoomChat(scope,message('Second'),now+1);
  const reloaded=load('../lib/room-chat-store.ts');
  await Promise.all(Array.from({length:32},(_,i)=>(i%2?chat:reloaded).appendRoomChat(scope,message('Concurrent '+i),now+2)));
  assert.equal((await reloaded.readRoomChat(scope,now+3)).length,34,'independent module copies serialize concurrent writes');
  for(const isolated of [{...scope,roomAssociation:'recreated-room'}, {...scope,studioId:'studio-two'}, {studioId:'studio-one/room-one',roomAssociation:'x'}, {studioId:'studio-one',roomAssociation:'room-one/x'}]){
   assert.deepEqual(await chat.readRoomChat(isolated,now+3),[],'same names cannot cross room incarnation or studio');
  }
  assert.equal((await chat.readRoomChat(scope,now+86400000-1)).length,34);
  const atBoundary=await chat.readRoomChat(scope,now+86400000);
  assert.equal(atBoundary.length,33,'exactly 24-hour-old entry expires, later entries remain');
  assert.ok(!JSON.parse(await fs.readFile(filename(scope),'utf8')).messages.some(m=>m.timestamp===now),'expired entry removed from disk');
  await chat.readRoomChat(scope,now+86400000+3);
  await assert.rejects(fs.access(filename(scope)),{code:'ENOENT'},'fully expired target is deleted');
  const fresh=await chat.appendRoomChat(scope,input,now+86400000+4);
  assert.equal(fresh.timestamp,now+86400000+4,'expired idempotence record does not live forever');
  for(const invalid of [{...message(),message:'x'.repeat(4001)}, {...message(),message:'   '}, {...message(),id:'not-a-uuid'}, {...message(),identity:''}])await assert.rejects(chat.appendRoomChat(scope,invalid,now));
  const safeBytes=await fs.readFile(filename(scope));
  await fs.writeFile(filename(scope),'broken-json');
  await assert.rejects(chat.readRoomChat(scope,now+1));
  await assert.rejects(chat.appendRoomChat(scope,message(),now+1));
  assert.equal(await fs.readFile(filename(scope),'utf8'),'broken-json','corruption fails closed without overwriting history');
  await fs.writeFile(filename(scope),safeBytes);
  const invalidEnvelope=JSON.parse(safeBytes);invalidEnvelope.messages[0].timestamp='bad';
  await fs.writeFile(filename(scope),JSON.stringify(invalidEnvelope));
  await assert.rejects(chat.readRoomChat(scope,now+1),/invalid|corrupt/i);
  await fs.writeFile(filename(scope),safeBytes);
  const mismatched=JSON.parse(safeBytes);mismatched.scopeKey='f'.repeat(64);
  await fs.writeFile(filename(scope),JSON.stringify(mismatched));
  await assert.rejects(chat.readRoomChat(scope,now+1),/invalid|corrupt/i,'copied room file cannot cross scope');
  await fs.writeFile(filename(scope),safeBytes);
  const writeScope={...scope,roomAssociation:'write-prune'};
  await chat.appendRoomChat(writeScope,message('Expired'),now);
  const latest=await chat.appendRoomChat(writeScope,message('Current'),now+86400000);
  assert.deepEqual(JSON.parse(await fs.readFile(filename(writeScope),'utf8')).messages,[latest],'append removes expired messages from disk');
  const fullScope={...scope,roomAssociation:'capacity'},cap=8*1024*1024;
  await chat.appendRoomChat(fullScope,message('Initialize'),now);
  const full=JSON.parse(await fs.readFile(filename(fullScope),'utf8'));
  const sample={...message('x'.repeat(4000)),timestamp:now};
  const count=Math.floor((cap-JSON.stringify({...full,messages:[]}).length)/(JSON.stringify(sample).length+1));
  full.messages=Array.from({length:count},()=>({...sample,id:randomUUID()}));
  const fullBytes=JSON.stringify(full);
  assert.ok(Buffer.byteLength(fullBytes)<=cap);
  await fs.writeFile(filename(fullScope),fullBytes);
  await assert.rejects(chat.appendRoomChat(fullScope,message('y'.repeat(4000)),now+1),/limit/i);
  assert.equal(await fs.readFile(filename(fullScope),'utf8'),fullBytes,'capacity rejection never truncates current history');
  const expiredScope={...scope,roomAssociation:'abandoned'},expired=await chat.appendRoomChat(expiredScope,message(),now);
  assert.equal(expired.timestamp,now);
  const cleanupDir=path.dirname(filename(scope));
  await fs.writeFile(path.join(cleanupDir,'unrelated.json'),'leave me');
  await chat.readRoomChat({studioId:'new',roomAssociation:'active'},now+86400000+3600001);
  await assert.rejects(fs.access(filename(expiredScope)),{code:'ENOENT'},'lazy cleanup removes abandoned expired chat');
  assert.equal(await fs.readFile(path.join(cleanupDir,'unrelated.json'),'utf8'),'leave me','cleanup only owns hash-named chat files');
  console.log('PASS room chat: durable module reload/concurrent writes, exact 24h purge, idempotence/conflicts, author/scope isolation, server time, validation, fail-closed corruption, bounded owned-file cleanup');
 }finally{await fs.rm(root,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
