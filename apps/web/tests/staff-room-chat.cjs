const assert = require('node:assert/strict');
const { load } = require('./load-typescript.cjs');
const { createStaffChatState, receiveStaffChat, markStaffChatRead, staffChatBadge, parseStaffChatBadgePreference } = load('../lib/staff-chat-state.ts');
const message = (id, timestamp, identity = 'guest-1', extra = {}) => ({ id, timestamp, message: id, from: { identity }, ...extra });
let state = createStaffChatState();
state = receiveStaffChat(state, [message('a', 1), message('self', 2, 'studio-panel-main')], false, 'studio-panel-main');
assert.equal(state.unread, 1, 'only remote messages count');
state = receiveStaffChat(state, [message('a', 1, 'guest-1', { message: 'edited', editTimestamp: 3 }), message('self', 2, 'studio-panel-main')], false, 'studio-panel-main');
assert.equal(state.unread, 1, 'edits and duplicate IDs do not count again');
assert.equal(state.messages[0].message, 'edited');
state = receiveStaffChat(state, [], false, 'studio-panel-main');
state = receiveStaffChat(state, [message('a', 1), message('b', 4)], false, 'studio-panel-main');
assert.equal(state.unread, 2, 'reconnect replay keeps the seen IDs');
state = receiveStaffChat(state, [message('c', 5)], true, 'studio-panel-main');
assert.equal(state.unread, 0, 'visible chat marks read, including new arrivals');
assert.equal(markStaffChatRead(receiveStaffChat(state, [message('d', 6)], false, '')).unread, 0);
assert.equal(receiveStaffChat(createStaffChatState(), [message('local', 1, '', { from: { isLocal: true } })], false, '').unread, 0);
const baseline = createStaffChatState([message('old-room', 1)]);
const fresh = receiveStaffChat(baseline, [message('old-room', 1), message('new-room', 2)], false, '');
assert.deepEqual(fresh.messages.map(item => item.id), ['new-room'], 'scope baseline never leaks old room history');
assert.equal(fresh.unread, 1);
const many = Array.from({ length: 2500 }, (_, index) => message(String(index), index + 1));
const history = receiveStaffChat(createStaffChatState(), many, false, '');
assert.equal(history.messages.length, many.length, 'the full session history remains accessible after 201 messages');
assert.equal(history.messages[0].id, '0');
assert.equal(receiveStaffChat(history, many, false, '').unread, history.unread, 'complete reconnect replay cannot inflate unread');
assert.equal(receiveStaffChat(history, [message('clock-skew', -100)], false, '').unread, history.unread + 1, 'a new ID counts even if the sender clock is behind');
assert.equal(staffChatBadge(100, true), '99+');
assert.equal(staffChatBadge(1, false), '', 'preference hides badge without changing unread');
assert.equal(staffChatBadge(0, true), '');
assert.equal(parseStaffChatBadgePreference(null), true);
assert.equal(parseStaffChatBadgePreference('false'), false);
assert.equal(parseStaffChatBadgePreference('true'), true);
assert.equal(parseStaffChatBadgePreference('{bad json'), true);
console.log('staff room chat state: PASS');

const restored = receiveStaffChat(createStaffChatState(), [message('saved-history', 100)], false, '', new Set(['saved-history']));
assert.equal(restored.unread, 0, 'restoring the24hour history does not mark old messages unread');
const expired = receiveStaffChat(receiveStaffChat(restored, [message('new-history',101)], false, ''), [], false, '', new Set(), 101);
assert.equal(expired.messages.length,0);assert.equal(expired.unread,0,'expiry removes unread IDs too');
