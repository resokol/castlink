const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { DatabaseSync } = require('node:sqlite');
const { load } = require('./load-typescript.cjs');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'castlink-observability-'));
const sample = at => ({ at, cpuPercent: 10, memoryUsedBytes: 50, memoryTotalBytes: 100, diskUsedBytes: 20, diskTotalBytes: 100, diskAvailableBytes: 75, networkInMbps: 0, networkOutMbps: 0, processRssBytes: 10, processUptimeSec: 60, configuredRooms: 1, activeRooms: 0, connections: 0, casters: 0, services: { web: 'ok', livekit: 'ok', roomStore: 'ok' } });
try {
  const { ServerObservabilityStore } = load('../lib/server-observability-store.ts');
  let now = 100000000;
  const filename = path.join(directory, 'runtime', 'history.sqlite');
  const options = { clock: () => now, metricLimit: 4, eventLimit: 3 };
  let store = new ServerObservabilityStore(filename, options);
  assert.equal(store.appendSample(sample(now - 86400001)), true);
  for (let n = 0; n < 6; n++) assert.equal(store.appendSample(sample(now - 90000 + n * 15000)), true);
  let view = store.readMetrics(3600000);
  assert.equal(view.history.length, 4); assert.equal(view.latest.at, now - 15000);
  assert.equal(fs.statSync(filename).mode & 0o777, 0o600);
  assert.equal(fs.statSync(path.dirname(filename)).mode & 0o777, 0o700);
  for (let n = 0; n < 5; n++) store.appendEvents([{ at: now - 1000 + n, level: n % 2 ? 'error' : 'info', event: 'test.event', service: 'castlink-web', fields: { status: 503 } }]);
  assert.equal(store.readEvents('all').events.length, 3);
  assert.equal(store.readEvents('error').events.length, 1);
  const page = store.readEvents('all', undefined, 2);
  assert.equal(page.events.length, 2); assert.ok(page.nextCursor);
  assert.equal(store.readEvents('all', page.nextCursor, 2).events.length, 1);
  store.close(); store = new ServerObservabilityStore(filename, options);
  assert.equal(store.readMetrics(3600000).history.length, 4, 'history survives reopening');
  const external = new DatabaseSync(filename);
  external.exec("INSERT INTO metrics(at,payload) VALUES (99999999,'{bad json');");
  assert.doesNotThrow(() => store.readMetrics(86400000), 'bad rows must not crash reads');
  external.exec('BEGIN IMMEDIATE');
  const started = performance.now();
  assert.equal(store.appendSample(sample(now)), false, 'busy DB degrades safely');
  assert.ok(performance.now() - started < 500, 'busy wait is bounded');
  external.exec('ROLLBACK'); external.close();
  now += 86400001;
  assert.equal(store.readMetrics(86400000).history.length, 0, 'expired data is not returned');
  assert.equal(store.readEvents('all').events.length, 0);
  store.close();
  const broken = path.join(directory, 'corrupt.sqlite'); fs.writeFileSync(broken, 'corrupt database');
  const unavailable = new ServerObservabilityStore(broken, options);
  assert.equal(unavailable.readMetrics(3600000).storage.state, 'unavailable');
  assert.equal(unavailable.appendSample(sample(now)), false); unavailable.close();
  const cappedFile = path.join(directory, 'capped.sqlite');
  const capped = new ServerObservabilityStore(cappedFile, { clock: () => now, maxBytes: 65536, walBytes: 2 * 1024 * 1024 });
  const events = Array.from({ length: 100 }, (_, n) => ({ at: now - n, level: 'info', event: 'capacity.test', service: 'castlink-web', fields: { requestId: 'x'.repeat(128), action: 'x'.repeat(128), reason: 'x'.repeat(128), code: 'x'.repeat(128) } }));
  assert.doesNotThrow(() => capped.appendEvents(events), 'disk pressure evicts or drops a bounded batch');
  assert.ok(capped.storage().droppedEvents > 0);
  assert.equal(capped.appendSample(sample(now)), true, 'a failed oversized event batch must not starve metrics');
  capped.close();
  assert.ok(fs.statSync(cappedFile).size <= 65536, 'SQLite page cap holds under a full transaction');
  const tinyFile = path.join(directory, 'tiny-wal.sqlite');
  const tiny = new ServerObservabilityStore(tinyFile, { clock: () => now, walBytes: 32768 });
  assert.equal(tiny.appendEvents(events), false, 'a WAL budget too small for a bounded transaction fails safely');
  assert.equal(tiny.appendSample(sample(now)), false);
  assert.ok(!fs.existsSync(`${tinyFile}-wal`) || fs.statSync(`${tinyFile}-wal`).size <= 32768);
  tiny.close();
  const fullFile = path.join(directory, 'full.sqlite');
  const full = new ServerObservabilityStore(fullFile, { clock: () => now, maxBytes: 32768, walBytes: 2 * 1024 * 1024 });
  let fullObserved = false;
  for (let n = 0; n < 100; n++) { if (!full.appendSample(sample(now - n))) { fullObserved = true; break; } }
  assert.equal(fullObserved, true, 'actual SQLITE_FULL is handled without throwing');
  assert.equal(full.storage().state, 'unavailable');
  now += 86400001;
  assert.equal(full.appendSample(sample(now)), true, 'expired rows are pruned before inserting after SQLITE_FULL');
  full.close(); assert.ok(fs.statSync(fullFile).size <= 32768);
  const pinnedFile = path.join(directory, 'pinned.sqlite');
  const pinned = new ServerObservabilityStore(pinnedFile, { clock: () => now });
  assert.equal(pinned.appendSample(sample(now)), true);
  const reader = new DatabaseSync(pinnedFile); reader.exec('BEGIN'); reader.prepare('SELECT count(*) FROM metrics').get();
  pinned.appendEvents(events.map(event => ({ ...event, at: now })));
  const beforeSize = fs.statSync(`${pinnedFile}-wal`).size;
  assert.equal(pinned.appendSample(sample(now + 1)), false, 'pinned WAL blocks additional writes');
  assert.equal(fs.statSync(`${pinnedFile}-wal`).size, beforeSize, 'foreign reader cannot make the WAL grow without bound');
  assert.ok(beforeSize <= 8 * 1024 * 1024);
  reader.exec('ROLLBACK'); reader.close();
  assert.equal(pinned.appendSample(sample(now)), true); pinned.close();
  console.log('PASS: actual SQLite persistence, retention/caps, private files, pagination, corrupt rows/database and bounded busy failures');
} finally { fs.rmSync(directory, { recursive: true, force: true }); }
