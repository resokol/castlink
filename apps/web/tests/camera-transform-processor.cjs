const assert = require('node:assert/strict'), fs = require('node:fs'), ts = require('typescript'), Module = require('node:module');
Module._extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { CameraTransformProcessor } = require('../lib/camera-transform-processor.ts');
const { DEFAULT_CAMERA_TRANSFORM } = require('../lib/camera-transform.ts');
const calls = [], outputs = [], videos = [];
let sourceStopped = false;
const source = { readyState: "live", enabled: true, getSettings: () => ({width: 640, height: 360, frameRate: 30}), stop: () => { sourceStopped = true; } };
global.MediaStream = class { constructor(tracks) { this.tracks = tracks; } };
const context = Object.fromEntries(['resetTransform', 'fillRect', 'save', 'translate', 'rotate', 'scale', 'drawImage', 'restore'].map(name => [name, (...args) => calls.push([name, ...args])]));
global.HTMLCanvasElement = class { getContext() { return context; } captureStream() { const track = { stopped: false, stop() { this.stopped = true; } }; outputs.push(track); return { getVideoTracks: () => [track] }; } };
global.document = { createElement(kind) { if (kind === 'canvas') return new HTMLCanvasElement(); const video = { readyState: 2, videoWidth: 640, videoHeight: 360, play: async () => {}, pause() {}, requestVideoFrameCallback(fn) { this.next = fn; return 1; }, cancelVideoFrameCallback() { this.cancelled = true; } }; videos.push(video); return video; } };
(async () => {
 const processor = new CameraTransformProcessor({...DEFAULT_CAMERA_TRANSFORM, zoom: 2, panX: .25, rotation: 90, flipX: true});
 await processor.init({kind: 'video', track: source});
 assert.ok(calls.some(call => call[0] === 'translate' && call[1] === 480 && call[2] === 180));
 assert.ok(calls.some(call => call[0] === 'scale' && call[1] === -2 && call[2] === 2));
 assert.ok(calls.some(call => call[0] === 'drawImage'));
 assert.equal(processor.processedTrack, outputs[0]);
 const beforePause = calls.length;
 processor.suspend(); assert.equal(processor.processedTrack.enabled, false); assert.equal(videos[0].srcObject, null);
 videos[0].next(); assert.equal(calls.length, beforePause, 'muted camera runs no draw loop even if an old frame callback fires');
 await processor.resume(); assert.equal(processor.processedTrack.enabled, true); assert.ok(calls.length > beforePause);
 await processor.restart({kind: 'video', track: source});
 assert.equal(outputs[0].stopped, true); assert.equal(videos[0].srcObject, null);
 assert.equal(processor.processedTrack, outputs[1]);
 await processor.destroy(); assert.equal(outputs[1].stopped, true); assert.equal(videos[1].cancelled, true);
 assert.equal(sourceStopped, false, 'processor never stops original camera or any microphone');
 console.log('CAMERA_TRANSFORM_PROCESSOR_PASS');
})().catch(error => {console.error(error); process.exitCode = 1;});
