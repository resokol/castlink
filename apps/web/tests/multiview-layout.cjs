const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
Module._extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { clampTile, resizeTile, gridScene, swapTilePositions, assignTileSource, createDraft, updateDraft, undoDraft, redoDraft } = require('../lib/multiview-layout.ts');
const tile = {id:'a',sourceIdentity:'guest-a',source:'camera',x:.1,y:.2,width:.4,height:.3,fit:'contain',muted:true};
const scene = {id:'scene',name:'Main',width:1920,height:1080,revision:2,tiles:[tile,{...tile,id:'b',sourceIdentity:'guest-b',x:.6}]};
assert.deepEqual(clampTile({...tile,x:-2,y:5,width:.7,height:.4}), {...tile,x:0,y:.6,width:.7,height:.4});
const safe = clampTile({...tile,x:NaN,y:Infinity,width:0,height:3});
assert.equal(safe.x,0); assert.equal(safe.y,0); assert.equal(safe.width,.02); assert.equal(safe.height,1);
const resized = resizeTile(tile,'nw',-.8,-.8);
assert.deepEqual([resized.x,resized.y,resized.width,resized.height],[0,0,.5,.5]);
const tiny = resizeTile(tile,'se',-2,-2);
assert.ok(Math.abs(tiny.width-.02)<1e-9 && Math.abs(tiny.height-.02)<1e-9);
assert.equal(tiny.x,tile.x); assert.equal(tiny.y,tile.y);
const grid = gridScene(scene,3,2,()=> 'fresh');
assert.equal(grid.tiles.length,6); assert.equal(grid.tiles[0].sourceIdentity,'guest-a');
assert.deepEqual([grid.tiles[4].x,grid.tiles[4].y,grid.tiles[4].width,grid.tiles[4].height],[1/3,1/2,1/3,1/2]);
assert.equal(grid.tiles[2].sourceIdentity,''); assert.equal(grid.tiles[2].muted,true);
assert.equal(new Set(grid.tiles.map(t=>t.id)).size,6, 'IDs remain unique even if an ID provider repeats');
assert.throws(()=>gridScene(scene,8,8),/32/); assert.throws(()=>gridScene(scene,0,2),/32/);
const swapped = swapTilePositions(scene,'a','b');
assert.equal(swapped.tiles[0].x,.6); assert.equal(swapped.tiles[1].x,.1);
assert.equal(swapped.tiles[0].sourceIdentity,'guest-a');
assert.strictEqual(swapTilePositions(scene,'missing','a'),scene);
const assigned = assignTileSource(scene,'a','guest-c','screen');
assert.equal(assigned.tiles[0].sourceIdentity,'guest-c'); assert.equal(assigned.tiles[0].source,'screen');
assert.equal(assigned.tiles[0].x,.1); assert.equal(scene.tiles[0].sourceIdentity,'guest-a');
const original = JSON.stringify(scene);
const draft = createDraft(scene);
const next = updateDraft(draft,assigned);
assert.deepEqual(undoDraft(next).present,scene);
assert.deepEqual(redoDraft(undoDraft(next)).present,assigned);
assert.equal(updateDraft(next,next.present),next,'No-op updates must not create undo steps');
const branch = updateDraft(undoDraft(next),swapped);
assert.equal(branch.future.length,0,'An edit after undo discards the redo branch');
next.present.tiles[0].x = .9;
assert.equal(JSON.stringify(scene),original,'Draft edits never mutate the applied scene');
console.log('PASS: multiview bounds, grids, source assignment, swap, and immutable draft history');
