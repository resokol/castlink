const assert = require('node:assert/strict');
const ts = require('typescript'), fs = require('node:fs'), vm = require('node:vm');
const mod = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync(require('node:path').join(__dirname, '../lib/camera-transform.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: mod.exports, module: mod });
const { parseCameraTransform: parse, DEFAULT_CAMERA_TRANSFORM: base, identityCameraTransform: identity } = mod.exports;
assert.ok(identity(parse(base)));
assert.equal(parse({...base, zoom: Infinity}), undefined);
assert.equal(parse({...base, panX: 1.1}), undefined);
assert.equal(parse({...base, rotation: 181}), undefined);
assert.equal(parse({...base, flipX: 'true'}), undefined);
assert.equal(parse({...base, unknown: 1}), undefined);
assert.equal(identity(parse({...base, zoom: 2})), false);
console.log('CAMERA_TRANSFORM_PASS');
