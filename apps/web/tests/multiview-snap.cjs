const assert = require('node:assert/strict');
require('./multiview-layout.cjs');
const fs = require('node:fs');
const path = require('node:path');
assert.ok(fs.existsSync(path.join(__dirname,'../lib/multiview-snap.ts')),'Snapping helpers must exist');
const {snapTile} = require('../lib/multiview-snap.ts');
const tile = {id:'a',sourceIdentity:'guest',source:'camera',x:.004,y:.2,width:.2,height:.2,fit:'contain',muted:true};
const options = {mode:'move',tiles:[],sceneWidth:1000,sceneHeight:500,tolerancePx:6};
const near = (n,expected)=>assert.ok(Math.abs(n-expected)<1e-9,`${n} != ${expected}`);
const left = snapTile(tile,options); near(left.tile.x,0); assert.deepEqual(left.guides,[{axis:'x',position:0}]);
assert.equal(tile.x,.004,'Snapping never changes the input draft');
const center = snapTile({...tile,x:.396,y:.393},options);
near(center.tile.x,.4); near(center.tile.y,.4); assert.deepEqual(center.guides,[{axis:'x',position:.5},{axis:'y',position:.5}]);
const far = snapTile({...tile,x:.02,y:.22},options); near(far.tile.x,.02); near(far.tile.y,.22); assert.deepEqual(far.guides,[]);
const other = {...tile,id:'b',x:.72,y:.8,width:.2,height:.1};
const edge = snapTile({...tile,x:.516,y:.22},{...options,tiles:[tile,other]});
near(edge.tile.x,.52); assert.deepEqual(edge.guides,[{axis:'x',position:.72}]);
const ignoredSelf = snapTile({...tile,x:.02,y:.22},{...options,tiles:[{...tile,x:.021,y:.221}]}); assert.deepEqual(ignoredSelf.guides,[]);
const offcanvas = snapTile({...tile,x:-.197,y:.22},options); near(offcanvas.tile.x,-.2); near(offcanvas.tile.width,.2);
const east = snapTile({...tile,x:.25,y:.22,width:.247},{...options,mode:'resize',edge:'e'});
near(east.tile.x,.25); near(east.tile.width,.25); assert.deepEqual(east.guides,[{axis:'x',position:.5}]);
const northWest = snapTile({...tile,x:.004,y:.007,width:.4,height:.4},{...options,mode:'resize',edge:'nw'});
near(northWest.tile.x,0); near(northWest.tile.y,0); near(northWest.tile.width,.404); near(northWest.tile.height,.407);
assert.deepEqual(northWest.guides,[{axis:'x',position:0},{axis:'y',position:0}]);
const minimum = snapTile({...tile,x:.49,width:.02,y:.22},{...options,mode:'resize',edge:'e',tolerancePx:12});
near(minimum.tile.width,.02); assert.deepEqual(minimum.guides,[],'Cannot snap an active edge through the opposite edge or below the minimum');
const maximum = snapTile({...tile,x:-.996,width:1.997,y:.22},{...options,mode:'resize',edge:'w',tiles:[{...other,x:-1}]});
near(maximum.tile.x,-.996); assert.deepEqual(maximum.guides,[],'Out-of-bounds anchors are not reported as active guides');
const disabled = snapTile(tile,{...options,sceneWidth:0,sceneHeight:NaN}); assert.deepEqual(disabled.guides,[]);
const tolerance = snapTile({...tile,x:.007},options); near(tolerance.tile.x,.007);
console.log('PASS: pixel-aware edge/center snapping for move/resize, other slots, offcanvas movement and bounded guides');
