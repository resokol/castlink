/** Translate only catalogued system messages; preserve external errors and user data. */
export function translateManagementMessage(message: string, t: (key: string, params?: Record<string, string | number>) => string): string {
  if (Object.hasOwn(knownSshMessages, message)) return t(knownSshMessages[message]);
  if (Object.hasOwn(managementMessages, message)) return t(message);
  const http = message.match(/^([\s\S]*) \(HTTP (\d{3})\)\.$/);
  if (http && Object.hasOwn(managementMessages, http[1])) return t("{message} (HTTP {status}).", { message: t(http[1]), status: http[2] });
  return message;
}
